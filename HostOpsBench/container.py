"""Container isolation for the interactive session control plane.

The interactive session's *control plane* (session daemon + gateway + injected
fault workers) must be unreachable by the operator's agent except through the
published gateway URL. Running them inside a container gives that boundary:
the agent connects to the gateway endpoint but has no shell into the container,
so it cannot ``kill`` the daemon/gateway from the host (a direct host ``kill``
bypasses every gateway-level policy).

Design (Linux/Kylin):

* ``--network host`` so the daemon's ephemeral control endpoint and the
  gateway's ephemeral port are reachable from the host loopback with **no code
  change** -- the daemon still picks free ports and writes them to the shared
  ``active.json``; the host CLI just reads them.
* the host repo is bind-mounted at the *same absolute path* inside the
  container, so the absolute paths baked into ``bootstrap.json`` (session dir,
  scenario files) resolve identically on both sides and ``active.json`` is
  shared.
* the default (isolated) PID namespace keeps the container's processes off the
  agent's ``ps``; combined with the gateway ``kill_process`` guard, the control
  plane cannot be torn down through either vector.
* ``--privileged`` so the live faults keep full fidelity (loop-mounted
  sandboxes, ``fio``, procfs, ``ss``). Without it the scenarios still run but
  degrade (bounded dir instead of a real fs), exactly as on a bare host.

macOS has no Linux container runtime with host networking, so container mode is
intended for the Linux/Kylin target; ``session start`` without ``--container``
keeps the in-process daemon (guarded, but killable by a same-user host shell).
"""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

IMAGE = "hostopsbench-session:local"
_DOCKERFILE = Path("docker/Dockerfile.session")

# Embedded so container mode works even when only the ``benchmark`` package was
# copied to the target host (the Dockerfile is materialized on demand).
# Base image + apt/pip mirrors are overridable so the build works on Kylin
# hosts that cannot reach Docker Hub / global archives (a very common case).
#   HOSTOPS_SESSION_BASE   base image FROM       (default ubuntu:22.04)
#   HOSTOPS_APT_MIRROR     apt mirror host        (default mirrors.aliyun.com)
#   HOSTOPS_PIP_INDEX      pip index-url          (default tsinghua)
_DOCKERFILE_TEXT = """\
# Isolated control plane for the interactive HostOpsBench session
# (`benchmark session start --container`). Auto-generated by benchmark/container.py.
FROM {base}

ENV DEBIAN_FRONTEND=noninteractive
RUN (sed -i 's|http://[a-z.]*archive.ubuntu.com/ubuntu/|http://{apt_mirror}/ubuntu/|g; s|http://security.ubuntu.com/ubuntu/|http://{apt_mirror}/ubuntu/|g' /etc/apt/sources.list 2>/dev/null || true) \\
    && apt-get update \\
    && apt-get install -y --no-install-recommends \\
        python3 python3-pip python3-venv \\
        procps iproute2 sysstat fio e2fsprogs mount util-linux \\
        ca-certificates \\
    && ln -sf /usr/bin/python3 /usr/local/bin/python \\
    && rm -rf /var/lib/apt/lists/*

WORKDIR /app

COPY pyproject.toml README.md ./
COPY mcp_servers ./mcp_servers
COPY benchmark ./benchmark

RUN pip install --no-cache-dir --break-system-packages -i {pip_index} -e "." \\
    || pip install --no-cache-dir -i {pip_index} -e "." \\
    || pip install --no-cache-dir --break-system-packages -e "." \\
    || pip install --no-cache-dir -e "."

ENV OPSAGENT_CONFIRM_SECRET="container-session-secret-0123456789"

CMD ["python", "-m", "benchmark", "session", "--help"]
"""


def _dockerfile_text() -> str:
    import os

    return _DOCKERFILE_TEXT.format(
        base=os.environ.get("HOSTOPS_SESSION_BASE", "ubuntu:22.04"),
        apt_mirror=os.environ.get("HOSTOPS_APT_MIRROR", "mirrors.aliyun.com"),
        pip_index=os.environ.get(
            "HOSTOPS_PIP_INDEX", "https://pypi.tuna.tsinghua.edu.cn/simple"
        ),
    )


class ContainerError(RuntimeError):
    """Raised when the container runtime is missing or a command fails."""


def _installed() -> list[str]:
    return [cli for cli in ("docker", "podman") if shutil.which(cli)]


def _daemon_ok(cli: str) -> bool:
    """True if ``cli info`` succeeds, i.e. the runtime is actually usable."""
    try:
        return _run([cli, "info"], timeout=30.0).returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


def runtime() -> str | None:
    """Return the first *usable* runtime CLI (daemon reachable / rootless ok).

    Prefers docker, but falls back to podman when docker's daemon is down so a
    working rootless podman is used automatically.
    """
    for cli in _installed():
        if _daemon_ok(cli):
            return cli
    return None


def require_runtime() -> str:
    cli = runtime()
    if cli is not None:
        return cli
    installed = _installed()
    if installed:
        raise ContainerError(
            f"found {', '.join(installed)} but no usable container runtime: the "
            "daemon is not running or your user cannot reach it. Fix with e.g. "
            "`sudo systemctl enable --now docker` and add your user to the docker "
            "group (`sudo usermod -aG docker $USER` then re-login), or install/use "
            "rootless `podman`."
        )
    raise ContainerError(
        "container mode requested but neither `docker` nor `podman` is on PATH; "
        "install one on the Linux/Kylin host, or start without --container."
    )


def _run(argv: list[str], *, timeout: float = 600.0) -> subprocess.CompletedProcess[str]:
    return subprocess.run(argv, capture_output=True, text=True, timeout=timeout)


def image_exists(cli: str, image: str = IMAGE) -> bool:
    return _run([cli, "image", "inspect", image]).returncode == 0


def build_image(cli: str, image: str = IMAGE, context: Path | None = None) -> None:
    """Build the session image if it is not already present."""
    if image_exists(cli, image):
        return
    context = context or Path.cwd()
    dockerfile = context / _DOCKERFILE
    # always (re)generate so HOSTOPS_SESSION_BASE / mirror overrides take effect
    # and container mode works even if only the benchmark package was copied
    dockerfile.parent.mkdir(parents=True, exist_ok=True)
    dockerfile.write_text(_dockerfile_text(), encoding="utf-8")
    proc = _run(
        [cli, "build", "-t", image, "-f", str(dockerfile), str(context)],
        timeout=1800.0,
    )
    if proc.returncode != 0:
        raise ContainerError(f"failed to build image {image}:\n{proc.stderr[-2000:]}")


def is_running(cli: str, name: str) -> bool:
    proc = _run([cli, "inspect", "-f", "{{.State.Running}}", name])
    return proc.returncode == 0 and proc.stdout.strip() == "true"


def exists(cli: str, name: str) -> bool:
    return _run([cli, "inspect", name]).returncode == 0


def remove(cli: str, name: str) -> None:
    """Force-remove the container (best effort)."""
    if exists(cli, name):
        _run([cli, "rm", "-f", name])


def run_daemon(
    cli: str,
    *,
    name: str,
    bootstrap: Path,
    repo: Path,
    confirm_secret: str,
    image: str = IMAGE,
    privileged: bool = True,
    python_bin: str = "python",
) -> None:
    """Launch the session daemon inside a detached container.

    The repo is mounted at its own absolute path so ``bootstrap`` (which holds
    absolute paths under the repo) resolves identically inside the container.
    ``python_bin`` is the interpreter used *inside* the container -- for a
    self-imported host-rootfs base image it should point at the same python
    that already has the project dependencies (e.g. an absolute conda path).
    """
    remove(cli, name)
    repo = repo.resolve()
    argv = [
        cli, "run", "-d",
        "--name", name,
        "--network", "host",
        "--init",
        # ``:z`` relabels the bind mount for SELinux (Kylin/RHEL-family enforce
        # it; ignored on non-SELinux docker) so the container can read the
        # mounted code and share active.json.
        "-v", f"{repo}:{repo}:z",
        "-w", str(repo),
        "-e", f"OPSAGENT_CONFIRM_SECRET={confirm_secret}",
        # imported rootfs images often carry a minimal PATH; make sure the
        # usual locations (and a common conda prefix) are reachable.
        "-e", "PATH=/opt/miniconda3/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
    ]
    if privileged:
        argv.append("--privileged")
    argv += [
        image,
        python_bin, "-m", "benchmark", "session", "_daemon", str(bootstrap),
    ]
    proc = _run(argv)
    if proc.returncode != 0:
        raise ContainerError(
            f"failed to start session container {name}:\n{proc.stderr[-2000:]}"
        )
